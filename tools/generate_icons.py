def generate_icons(scale=16):
    out_dir = "slides/assets/icons"
    os.makedirs(out_dir, exist_ok=True)
    
    # Generate individual icons
    for name, rows in ICONS.items():
        assert len(rows) == 16, f"Icon {name} has {len(rows)} rows"
        for r_idx, r in enumerate(rows):
            assert len(r) == 16, f"Icon {name} row {r_idx} has {len(r)} chars: '{r}'"
        
        img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
        for y, row in enumerate(rows):
            for x, char in enumerate(row):
                color = PALETTE.get(char, (0, 0, 0, 0))
                img.putpixel((x, y), color)
        
        scaled = img.resize((16 * scale, 16 * scale), Image.NEAREST)
        scaled.save(os.path.join(out_dir, f"{name}.png"))
    
    # Generate Sprite Sheet (4 columns x 5 rows)
    cols = 5
    rows = 4
    sheet_w = cols * (16 * scale + 16) + 16
    sheet_h = rows * (16 * scale + 16) + 16
    sheet = Image.new("RGBA", (sheet_w, sheet_h), (255, 248, 231, 255)) # Cream bg
    
    icon_names = list(ICONS.keys())
    for idx, name in enumerate(icon_names):
        c = idx % cols
        r = idx // cols
        icon_img = Image.open(os.path.join(out_dir, f"{name}.png"))
        x = 16 + c * (16 * scale + 16)
        y = 16 + r * (16 * scale + 16)
        sheet.alpha_composite(icon_img, (x, y))
    
    sheet_path = os.path.join(out_dir, "sprite_sheet.png")
    sheet.save(sheet_path)
    print(f"Generated {len(ICONS)} icons and saved sprite sheet to {sheet_path}")

if __name__ == "__main__":
    generate_icons()
